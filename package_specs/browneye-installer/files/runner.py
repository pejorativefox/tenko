"""Command execution and dry-run planning.

Every external program is invoked as an argv list.  There is no
``shell=True`` anywhere in the installer.  Mutating commands are recorded
into ``/run/browneye/plan.sh`` in dry-run mode and are never executed.

The runner is deliberately small and dependency free so the disk planner can
emit a list of :class:`Command` objects and the install pipeline can execute
them without knowing how the plan was produced.
"""

from __future__ import annotations

import os
import shlex
import subprocess
import time
from dataclasses import dataclass, field
from typing import Callable, Iterable, Mapping, Sequence

from log import Logger

MIB = 1024 * 1024
GIB = 1024 * MIB

DEFAULT_PATH = "/usr/sbin:/usr/bin:/sbin:/bin"
DEFAULT_ENV = {
    "LC_ALL": "C",
    "LANG": "C",
    "PATH": DEFAULT_PATH,
}

_SECRET_ARG_PREFIXES = ("--password=", "--passwd=")
_SECRET_ARG_FLAGS = {"--password", "--passwd", "-p"}


class CommandError(RuntimeError):
    """A command exited non-zero (or could not be executed)."""

    def __init__(
        self,
        argv: Sequence[str],
        rc: int,
        output: str = "",
        *,
        step: str | None = None,
    ) -> None:
        self.argv = list(argv)
        self.rc = rc
        self.output = output or ""
        self.step = step
        tail = "\n".join(self.output.splitlines()[-20:])
        message = "command failed (rc={}): {}".format(rc, shlex.join(self.argv))
        if tail:
            message += "\n" + tail
        super().__init__(message)


@dataclass(frozen=True)
class Result:
    argv: tuple[str, ...]
    rc: int
    output: str
    duration_ms: int
    dry_run: bool = False

    @property
    def ok(self) -> bool:
        return self.rc == 0


@dataclass(frozen=True)
class Command:
    """A single external command emitted by the planner.

    ``read_only`` commands are allowed to run in dry-run mode (probes such as
    ``lsblk`` and ``sfdisk --json``).  Everything else is recorded into the
    dry-run plan instead of being executed.
    """

    argv: tuple[str, ...]
    step: str = ""
    description: str = ""
    stdin: str | None = None
    stdin_path: str | None = None
    stdout_path: str | None = None
    append: bool = False
    destructive: bool = True
    read_only: bool = False
    allow_failure: bool = False
    stdin_redacted: bool = True
    timeout: float | None = None
    cwd: str | None = None


def _coerce_argv(argv: Sequence[str] | str) -> tuple[str, ...]:
    if isinstance(argv, str):
        raise TypeError("argv must be a sequence, not a shell string")
    return tuple(str(item) for item in argv)


class CommandRunner:
    def __init__(
        self,
        logger: Logger | None = None,
        *,
        dry_run: bool = False,
        plan_path: str = "/run/browneye/plan.sh",
        env: Mapping[str, str] | None = None,
        console: Callable[[str], None] | None = None,
    ) -> None:
        self.logger = logger
        self.dry_run = dry_run
        self.plan_path = plan_path
        self.console = console
        self.env = os.environ.copy()
        self.env.update(DEFAULT_ENV)
        if env:
            self.env.update({str(k): str(v) for k, v in env.items()})
        self.planned: list[Command] = []
        self._plan_started = False

    # ------------------------------------------------------------------
    # Dry-run plan
    # ------------------------------------------------------------------
    def _start_plan(self) -> None:
        if self._plan_started:
            return
        self._plan_started = True
        path = self.plan_path
        if not path:
            return
        try:
            directory = os.path.dirname(path)
            if directory:
                os.makedirs(directory, exist_ok=True)
            with open(path, "w", encoding="utf-8") as handle:
                handle.write("#!/bin/sh\n")
                handle.write("set -u\n")
                handle.write(
                    "# Generated by browneye-installer --dry-run; review before running.\n"
                )
                handle.write("# Mutating commands were NOT executed.\n\n")
        except OSError:
            self.plan_path = ""

    def _plan_block(self, command: Command) -> str:
        lines: list[str] = []
        if command.description:
            lines.append("# " + command.description)
        line = shlex.join(list(command.argv))
        if command.stdout_path:
            redir = ">>" if command.append else ">"
            line += " " + redir + " " + shlex.quote(command.stdout_path)
        stdin_text = command.stdin
        if stdin_text is None and command.stdin_path:
            line += " < " + shlex.quote(command.stdin_path)
            stdin_text = None
        if stdin_text is not None:
            if command.stdin_redacted:
                lines.append(line + " <<'EOF'")
                lines.append("# <redacted stdin>")
                lines.append("EOF")
            else:
                delimiter = "BROWNEYE_EOF"
                while delimiter in stdin_text:
                    delimiter += "_X"
                lines.append(line + " <<'" + delimiter + "'")
                lines.append(stdin_text.rstrip("\n"))
                lines.append(delimiter)
        else:
            lines.append(line)
        if command.allow_failure and stdin_text is None:
            lines[-1] += " || true"
        return "\n".join(lines) + "\n\n"

    def _record_plan(self, command: Command) -> None:
        self.planned.append(command)
        if self.dry_run and self.plan_path:
            self._start_plan()
            if self.plan_path:
                try:
                    with open(self.plan_path, "a", encoding="utf-8") as handle:
                        handle.write(self._plan_block(command))
                except OSError:
                    pass
        if self.logger is not None:
            self.logger.record(
                "info",
                "planned",
                step=command.step or None,
                argv=list(command.argv),
                destructive=command.destructive,
                read_only=command.read_only,
                description=command.description or None,
            )

    # ------------------------------------------------------------------
    # Execution
    # ------------------------------------------------------------------
    def run(
        self,
        argv: Sequence[str] | str,
        *,
        step: str = "",
        description: str = "",
        destructive: bool = True,
        read_only: bool = False,
        timeout: float | None = None,
        stdin: str | None = None,
        stdin_redacted: bool = True,
        stdout_path: str | None = None,
        append: bool = False,
        allow_failure: bool = False,
        cwd: str | None = None,
        on_line: Callable[[str], None] | None = None,
    ) -> Result:
        command = Command(
            argv=_coerce_argv(argv),
            step=step,
            description=description,
            stdin=stdin,
            stdout_path=stdout_path,
            append=append,
            destructive=destructive,
            read_only=read_only,
            allow_failure=allow_failure,
            stdin_redacted=stdin_redacted,
            timeout=timeout,
            cwd=cwd,
        )
        return self.run_command(command, on_line=on_line)

    def run_command(
        self,
        command: Command,
        *,
        on_line: Callable[[str], None] | None = None,
    ) -> Result:
        if self.dry_run and not command.read_only:
            self._record_plan(command)
            return Result(command.argv, 0, "", 0, dry_run=True)

        stdin_text = command.stdin
        if stdin_text is None and command.stdin_path:
            try:
                with open(command.stdin_path, "r", encoding="utf-8") as handle:
                    stdin_text = handle.read()
            except OSError as exc:
                return self._failure(
                    command, 126, f"cannot read stdin file {command.stdin_path}: {exc}"
                )

        started = time.monotonic()
        try:
            completed = subprocess.run(
                list(command.argv),
                input=stdin_text,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=command.timeout,
                cwd=command.cwd,
                env=self.env,
                shell=False,
            )
            rc = completed.returncode
            output = completed.stdout or ""
        except FileNotFoundError:
            rc = 127
            output = "executable not found: {}".format(command.argv[0])
        except PermissionError:
            rc = 126
            output = "permission denied: {}".format(command.argv[0])
        except subprocess.TimeoutExpired as exc:
            rc = 124
            output = (exc.stdout or "") if isinstance(exc.stdout, str) else ""
            output += "\ntimed out after {} seconds".format(command.timeout)
        except OSError as exc:
            rc = 126
            output = str(exc)

        duration_ms = int((time.monotonic() - started) * 1000)

        if command.stdout_path:
            try:
                directory = os.path.dirname(command.stdout_path)
                if directory:
                    os.makedirs(directory, exist_ok=True)
                mode = "a" if command.append else "w"
                with open(command.stdout_path, mode, encoding="utf-8") as handle:
                    handle.write(output)
            except OSError as exc:
                if not command.allow_failure:
                    return self._failure(
                        command, 126, f"cannot write {command.stdout_path}: {exc}"
                    )

        stdin_log = None
        if stdin_text is not None:
            stdin_log = "<redacted>" if command.stdin_redacted else stdin_text
        if self.logger is not None:
            self.logger.command(
                command.argv,
                rc,
                duration_ms,
                step=command.step or None,
                output_tail=output,
                stdin_log=stdin_log,
            )
        if on_line is not None:
            for line in output.splitlines():
                on_line(line)

        result = Result(command.argv, rc, output, duration_ms)
        if rc != 0:
            if command.allow_failure:
                if self.logger is not None:
                    self.logger.warning(
                        "command-failed-allowed",
                        step=command.step or None,
                        argv=list(command.argv),
                        rc=rc,
                        tail=output[-1000:],
                    )
            else:
                raise CommandError(
                    command.argv, rc, output, step=command.step or None
                )
        return result

    def _failure(self, command: Command, rc: int, output: str) -> Result:
        if self.logger is not None:
            self.logger.command(
                command.argv, rc, 0, step=command.step or None, output_tail=output
            )
        if command.allow_failure:
            return Result(command.argv, rc, output, 0)
        raise CommandError(command.argv, rc, output, step=command.step or None)

    def run_streaming(
        self,
        argv: Sequence[str] | str,
        on_line: Callable[[str], None],
        *,
        step: str = "",
        description: str = "",
        destructive: bool = True,
        stdin: str | None = None,
        stdin_redacted: bool = True,
        allow_failure: bool = False,
        timeout: float | None = None,
        cwd: str | None = None,
    ) -> Result:
        command = Command(
            argv=_coerce_argv(argv),
            step=step,
            description=description,
            stdin=stdin,
            destructive=destructive,
            read_only=False,
            allow_failure=allow_failure,
            stdin_redacted=stdin_redacted,
            timeout=timeout,
            cwd=cwd,
        )
        if self.dry_run:
            self._record_plan(command)
            return Result(command.argv, 0, "", 0, dry_run=True)

        started = time.monotonic()
        tail: list[str] = []
        try:
            process = subprocess.Popen(
                list(command.argv),
                stdin=subprocess.PIPE if stdin is not None else subprocess.DEVNULL,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                text=True,
                encoding="utf-8",
                errors="replace",
                cwd=command.cwd,
                env=self.env,
                shell=False,
            )
        except (FileNotFoundError, PermissionError, OSError) as exc:
            rc = 127 if isinstance(exc, FileNotFoundError) else 126
            return self._failure(command, rc, str(exc))

        if stdin is not None and process.stdin is not None:
            try:
                process.stdin.write(stdin)
                process.stdin.close()
            except (BrokenPipeError, OSError):
                pass

        assert process.stdout is not None
        for line in process.stdout:
            line = line.rstrip("\n")
            tail.append(line)
            if len(tail) > 500:
                del tail[:250]
            on_line(line)
        process.stdout.close()
        rc = process.wait()
        duration_ms = int((time.monotonic() - started) * 1000)
        output = "\n".join(tail)

        stdin_log = None
        if stdin is not None:
            stdin_log = "<redacted>" if stdin_redacted else stdin
        if self.logger is not None:
            self.logger.command(
                command.argv,
                rc,
                duration_ms,
                step=command.step or None,
                output_tail=output,
                stdin_log=stdin_log,
            )
        result = Result(command.argv, rc, output, duration_ms)
        if rc != 0:
            if command.allow_failure:
                if self.logger is not None:
                    self.logger.warning(
                        "command-failed-allowed",
                        step=command.step or None,
                        argv=list(command.argv),
                        rc=rc,
                        tail=output[-1000:],
                    )
            else:
                raise CommandError(
                    command.argv, rc, output, step=command.step or None
                )
        return result

    # ------------------------------------------------------------------
    # Filesystem helpers (dry-run aware)
    # ------------------------------------------------------------------
    def makedirs(self, path: str, mode: int = 0o755, *, step: str = "", allow_failure: bool = False) -> None:
        if self.dry_run:
            self._record_plan(
                Command(
                    argv=("mkdir", "-p", path),
                    step=step,
                    description="create directory " + path,
                    destructive=True,
                    allow_failure=allow_failure,
                )
            )
            return
        try:
            os.makedirs(path, mode=mode, exist_ok=True)
        except OSError:
            if not allow_failure:
                raise

    def write_file(
        self,
        path: str,
        content: str,
        *,
        mode: int = 0o644,
        step: str = "",
        append: bool = False,
        log_content: bool = True,
        allow_failure: bool = False,
    ) -> None:
        if self.dry_run:
            command = Command(
                argv=("cat",),
                step=step,
                description=("append to " if append else "write ") + path,
                stdin=content,
                stdout_path=path,
                append=append,
                destructive=True,
                stdin_redacted=not log_content,
                allow_failure=allow_failure,
            )
            self._record_plan(command)
            return
        try:
            directory = os.path.dirname(path)
            if directory:
                os.makedirs(directory, exist_ok=True)
            with open(path, "a" if append else "w", encoding="utf-8") as handle:
                handle.write(content)
            try:
                os.chmod(path, mode)
            except OSError:
                pass
        except OSError:
            if not allow_failure:
                raise
        if self.logger is not None:
            self.logger.record(
                "info",
                "write-file",
                step=step or None,
                path=path,
                bytes=len(content.encode("utf-8")),
                mode=oct(mode),
                append=append,
                content=content if log_content else "<redacted>",
            )

    def read_text(self, path: str) -> str | None:
        try:
            with open(path, "r", encoding="utf-8", errors="replace") as handle:
                return handle.read()
        except OSError:
            return None


def command(
    *argv: str,
    step: str = "",
    description: str = "",
    **kwargs,
) -> Command:
    """Tiny helper used by disk.py and install.py."""

    return Command(
        argv=tuple(str(item) for item in argv),
        step=step,
        description=description,
        **kwargs,
    )
