import tempfile
import unittest

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "files"))

from install import ConfigError, InstallConfig  # noqa: E402
from log import Logger, null_logger  # noqa: E402
from runner import CommandError, CommandRunner  # noqa: E402


class RunnerTest(unittest.TestCase):
    def test_dry_run_records_mutations_and_does_not_execute(self):
        with tempfile.TemporaryDirectory() as temp:
            plan = os.path.join(temp, "plan.sh")
            target = os.path.join(temp, "should-not-exist")
            runner = CommandRunner(null_logger(), dry_run=True, plan_path=plan)
            result = runner.run(["touch", target])
            self.assertTrue(result.dry_run)
            self.assertEqual(result.rc, 0)
            self.assertFalse(os.path.exists(target))
            text = pathlib.Path(plan).read_text()
            self.assertIn("touch " + target, text)
            self.assertIn("Generated by browneye-installer --dry-run", text)

    def test_dry_run_still_executes_read_only_commands(self):
        with tempfile.TemporaryDirectory() as temp:
            runner = CommandRunner(
                null_logger(), dry_run=True, plan_path=os.path.join(temp, "plan.sh")
            )
            result = runner.run(["/bin/echo", "hello"], read_only=True)
            self.assertFalse(result.dry_run)
            self.assertEqual(result.output.strip(), "hello")

    def test_password_stdin_is_redacted_in_plan_and_log(self):
        with tempfile.TemporaryDirectory() as temp:
            log_path = os.path.join(temp, "install.jsonl")
            plan = os.path.join(temp, "plan.sh")
            logger = Logger(log_path, human_path=os.path.join(temp, "install.log"))
            self.addCleanup(logger.close)
            runner = CommandRunner(logger, dry_run=True, plan_path=plan)
            runner.run(
                ["chroot", "/mnt/target", "/usr/sbin/chpasswd"],
                stdin="admin:super-secret\n",
                stdin_redacted=True,
            )
            plan_text = pathlib.Path(plan).read_text()
            log_text = pathlib.Path(log_path).read_text()
            human_text = pathlib.Path(os.path.join(temp, "install.log")).read_text()
            self.assertNotIn("super-secret", plan_text)
            self.assertNotIn("super-secret", log_text)
            self.assertNotIn("super-secret", human_text)

    def test_write_file_is_dry_run_aware(self):
        with tempfile.TemporaryDirectory() as temp:
            target = os.path.join(temp, "fstab")
            plan = os.path.join(temp, "plan.sh")
            runner = CommandRunner(null_logger(), dry_run=True, plan_path=plan)
            runner.write_file(target, "UUID=abc / ext4 defaults 0 1\n")
            self.assertFalse(os.path.exists(target))
            text = pathlib.Path(plan).read_text()
            self.assertIn("UUID=abc / ext4 defaults 0 1", text)

    def test_nonzero_rc_raises(self):
        runner = CommandRunner(null_logger(), dry_run=False)
        with self.assertRaises(CommandError):
            runner.run(["/bin/false"], read_only=True)

    def test_allow_failure_returns_result(self):
        runner = CommandRunner(null_logger(), dry_run=False)
        result = runner.run(["/bin/false"], read_only=True, allow_failure=True)
        self.assertEqual(result.rc, 1)

    def test_command_with_stdin(self):
        runner = CommandRunner(null_logger(), dry_run=False)
        result = runner.run(
            ["/bin/cat"], stdin="hello\n", read_only=True
        )
        self.assertEqual(result.output, "hello\n")


class ConfigTest(unittest.TestCase):
    def _layout(self):
        return {
            "disks": [
                {
                    "path": "/dev/vda",
                    "serial": "QM00001",
                    "size_bytes": 21474836480,
                    "delete_partitions": [],
                    "partitions": [
                        {
                            "role": "esp",
                            "fstype": "vfat",
                            "mountpoint": "/boot",
                            "size_mib": 1024,
                        },
                        {
                            "role": "swap",
                            "fstype": "swap",
                            "size_mib": 2048,
                        },
                        {
                            "role": "root",
                            "fstype": "ext4",
                            "mountpoint": "/",
                        },
                    ],
                }
            ]
        }

    def _mapping(self, **overrides):
        data = {
            "version": 2,
            "layout": self._layout(),
            "package_set": "desktop",
            "hostname": "browneye",
            "admin": {"username": "admin", "password": "test-password"},
            "confirm": {"disk": "/dev/vda", "phrase": "ERASE"},
        }
        data.update(overrides)
        return data

    def test_valid_config(self):
        config = InstallConfig.from_mapping(self._mapping())
        self.assertEqual(config.validate(), [])
        self.assertIn("xfce-desktop", config.packages)
        self.assertNotIn("test-password", json.dumps(config.public_dict()))

    def test_unknown_key_is_rejected(self):
        with self.assertRaises(ConfigError):
            InstallConfig.from_mapping(self._mapping(typo=True))

    def test_v1_is_rejected(self):
        with self.assertRaises(ConfigError):
            InstallConfig.from_mapping({"version": 1})

    def test_confirmation_is_required(self):
        config = InstallConfig.from_mapping(
            self._mapping(confirm={"disk": "/dev/vdb", "phrase": "erase"})
        )
        issues = config.validate()
        self.assertTrue(any("disk path" in issue for issue in issues))
        self.assertTrue(any("ERASE" in issue for issue in issues))

    def test_hostname_and_missing_root(self):
        layout = self._layout()
        layout["disks"][0]["partitions"] = [
            item
            for item in layout["disks"][0]["partitions"]
            if item["role"] != "root"
        ]
        config = InstallConfig.from_mapping(
            self._mapping(layout=layout, hostname="bad host name")
        )
        issues = config.validate()
        self.assertTrue(any("root partition" in issue for issue in issues))
        self.assertTrue(any("hostname" in issue for issue in issues))

    def test_multiple_disks(self):
        layout = self._layout()
        layout["disks"].append(
            {
                "path": "/dev/vdb",
                "partitions": [
                    {
                        "role": "data",
                        "fstype": "btrfs",
                        "mountpoint": "/home",
                    }
                ],
            }
        )
        config = InstallConfig.from_mapping(self._mapping(layout=layout))
        self.assertEqual(config.validate(), [])
        self.assertEqual(config.root_disk_path, "/dev/vda")
        self.assertEqual(config.disk_paths, ("/dev/vda", "/dev/vdb"))
        self.assertEqual(config.layout.disks[1].partitions[0].fstype, "btrfs")

    def test_base_package_set(self):
        config = InstallConfig.from_mapping(self._mapping(package_set="base"))
        self.assertNotIn("xfce-desktop", config.packages)
        self.assertIn("browneye-base-runtime", config.packages)


if __name__ == "__main__":
    unittest.main()
