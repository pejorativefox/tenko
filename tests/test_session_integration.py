"""Autostart, XSettings and startup-notification packaging checks.

The X server side of issue #36 lives in ``scripts/fdo_session_check.sh`` and
runs inside a live session.  This module is the headless half: it follows the
autostart files that the package specs and file lists put in
``/etc/xdg/autostart`` and exercises the Autostart 0.5 visibility rules.

Desktop entry sources are generated by the upstream builds, not checked in
here.  When no source is available the content checks skip with a reason
instead of failing; set ``TENKO_ROOT`` to an extracted installed root tree
(for example ``build/rootfs-desktop``) to validate the real payload.
"""

import configparser
import os
import re
import shutil
import subprocess
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SPECS = REPO_ROOT / "package_specs"
AUTOSTART_PREFIX = "/etc/xdg/autostart/"

PATH_DIRECTIVE = re.compile(
    r"^%(doc|config|attr|verify|dir|defattr|license)\b[^ ]*\s*"
)
ATTR_DIRECTIVE = re.compile(r"^%attr\([^)]*\)\s*")
MACROS = (
    ("%{_sysconfdir}", "/etc"),
    ("%{_prefix}", "/usr"),
    ("%{_bindir}", "/usr/bin"),
    ("%{_sbindir}", "/usr/sbin"),
    ("%{_libdir}", "/usr/lib64"),
    ("%{_libexecdir}", "/usr/libexec"),
)
COMMAND_DIRS = ("/usr/bin/", "/usr/sbin/", "/bin/", "/sbin/",
                "/usr/libexec/", "/usr/lib/")

EXPECTED_AUTOSTART = (
    "/etc/xdg/autostart/at-spi-dbus-bus.desktop",
    "/etc/xdg/autostart/nm-applet.desktop",
    "/etc/xdg/autostart/pulseaudio.desktop",
    "/etc/xdg/autostart/xdg-user-dirs.desktop",
    "/etc/xdg/autostart/xfce4-power-manager.desktop",
    "/etc/xdg/autostart/xfsettingsd.desktop",
)


def read_text(path):
    with open(path, encoding="utf-8", errors="replace") as handle:
        return handle.read()


def normalize_path(line):
    """Return an absolute packaged path, or an empty string for metadata."""
    path = line.strip()
    if not path or path.startswith("#"):
        return ""
    path = PATH_DIRECTIVE.sub("", path)
    path = ATTR_DIRECTIVE.sub("", path)
    for macro, value in MACROS:
        path = path.replace(macro, value)
    if not path.startswith("/"):
        return ""
    return path


def inline_files(spec_text):
    """Yield the inline ``%files`` entries of a spec."""
    section_start = re.compile(r"^%files\b")
    other_section = re.compile(r"^%[a-zA-Z]")
    in_files = False
    for raw in spec_text.splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        if section_start.match(line):
            in_files = True
            continue
        if not in_files:
            continue
        if other_section.match(line):
            in_files = False
            continue
        path = normalize_path(line)
        if path:
            yield path


def packaged_paths():
    """Map every packaged path to the set of packages that own it."""
    owners = {}
    for filelist in sorted(SPECS.glob("*/files/*.filelist")):
        package = filelist.parent.parent.name
        for line in filelist.read_text(
                encoding="utf-8", errors="replace").splitlines():
            path = normalize_path(line)
            if path:
                owners.setdefault(path, set()).add(package)
    for spec in sorted(SPECS.glob("*/*.spec")):
        package = spec.parent.name
        for path in inline_files(spec.read_text(
                encoding="utf-8", errors="replace")):
            owners.setdefault(path, set()).add(package)
    return owners


def autostart_entries():
    return {
        path: packages
        for path, packages in packaged_paths().items()
        if path.startswith(AUTOSTART_PREFIX) and path.endswith(".desktop")
    }


def find_source(path):
    """Find a checked-in source for a packaged path, if there is one."""
    name = Path(path).name
    candidates = []
    root = os.environ.get("TENKO_ROOT")
    if root:
        candidates.append(Path(root) / path.lstrip("/"))
    candidates.extend(sorted(SPECS.glob("*/files/" + name)))
    candidates.extend(sorted(SPECS.glob("*/" + name)))
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return None


def parse_desktop(path):
    parser = configparser.RawConfigParser(interpolation=None, strict=False)
    parser.optionxform = str
    parser.read_string(read_text(path))
    if not parser.has_section("Desktop Entry"):
        raise AssertionError("%s has no [Desktop Entry] section" % path)
    return parser


def try_exec_available(try_exec, shipped_paths):
    """True when TryExec is an absolute path or a command we package."""
    if not try_exec:
        return True
    if try_exec.startswith("/"):
        return try_exec in shipped_paths
    return any(prefix + try_exec in shipped_paths for prefix in COMMAND_DIRS)


def autostart_visible(system, user=None, desktop="XFCE"):
    """Model Autostart 0.5 visibility for one desktop entry.

    A user entry replaces the system entry with the same file name.  The
    effective entry is hidden by ``Hidden=true``, by an ``OnlyShowIn`` list
    that does not contain the desktop, or by a ``NotShowIn`` list that does.
    """
    entry = user if user is not None else system
    if entry is None:
        return False
    if str(entry.get("Hidden", "")).strip().lower() == "true":
        return False
    only_show = [item.strip() for item in
                 entry.get("OnlyShowIn", "").split(";") if item.strip()]
    if only_show and desktop not in only_show:
        return False
    not_show = [item.strip() for item in
                entry.get("NotShowIn", "").split(";") if item.strip()]
    if desktop in not_show:
        return False
    return True


def requires(path):
    """Return the Requires: package names from a spec file."""
    result = set()
    for line in read_text(path).splitlines():
        match = re.match(r"^Requires:\s*(\S+)", line)
        if match:
            result.add(match.group(1))
    return result


class AutostartPackagingTest(unittest.TestCase):
    def test_specs_and_filelists_ship_the_expected_entries(self):
        entries = autostart_entries()
        for path in EXPECTED_AUTOSTART:
            self.assertIn(path, entries, path)
        for path in entries:
            self.assertTrue(path.endswith(".desktop"), path)
            self.assertTrue(path.startswith(AUTOSTART_PREFIX), path)

    def test_autostart_sources_validate_when_available(self):
        entries = autostart_entries()
        sources = {
            path: find_source(path)
            for path in entries
        }
        sources = {
            path: source for path, source in sources.items() if source
        }
        if not sources:
            self.skipTest(
                "no autostart sources in the repository (upstream RPM "
                "payload); set TENKO_ROOT to an extracted root tree")
        validator = shutil.which("desktop-file-validate")
        if validator is None:
            self.skipTest("desktop-file-validate is not installed")
        for path, source in sorted(sources.items()):
            result = subprocess.run(
                [validator, str(source)],
                capture_output=True, text=True,
            )
            self.assertEqual(
                result.returncode, 0,
                "%s: %s" % (path, result.stdout + result.stderr))

    def test_entries_declare_type_application(self):
        entries = autostart_entries()
        sources = {
            path: find_source(path)
            for path in entries
        }
        sources = {
            path: source for path, source in sources.items() if source
        }
        if not sources:
            self.skipTest(
                "no autostart sources in the repository (upstream RPM "
                "payload); set TENKO_ROOT to an extracted root tree")
        for path, source in sorted(sources.items()):
            parser = parse_desktop(source)
            self.assertEqual(
                parser.get("Desktop Entry", "Type", fallback=""),
                "Application", path)

    def test_try_exec_is_absolute_or_a_packaged_command(self):
        shipped = set(packaged_paths())
        self.assertTrue(
            try_exec_available("/usr/bin/nm-applet", shipped))
        self.assertTrue(try_exec_available("nm-applet", shipped))
        self.assertFalse(
            try_exec_available("/usr/bin/tenko-not-installed", shipped))
        self.assertFalse(
            try_exec_available("tenko-not-installed", shipped))

        entries = autostart_entries()
        sources = {
            path: find_source(path)
            for path in entries
        }
        sources = {
            path: source for path, source in sources.items() if source
        }
        if not sources:
            self.skipTest(
                "no autostart sources in the repository (upstream RPM "
                "payload); set TENKO_ROOT to an extracted root tree")
        for path, source in sorted(sources.items()):
            parser = parse_desktop(source)
            try_exec = parser.get(
                "Desktop Entry", "TryExec", fallback="").strip()
            self.assertTrue(
                try_exec_available(try_exec, shipped),
                "%s: TryExec %r is not packaged" % (path, try_exec))

    def test_user_hidden_override_suppresses_system_entry(self):
        system = {"Hidden": "false", "OnlyShowIn": "XFCE;"}
        user = {"Hidden": "true"}
        self.assertTrue(autostart_visible(system, desktop="XFCE"))
        self.assertFalse(autostart_visible(system, user, "XFCE"))

    def test_only_show_in_matches_xfce(self):
        self.assertFalse(
            autostart_visible({"OnlyShowIn": "GNOME;"}, desktop="XFCE"))
        self.assertTrue(
            autostart_visible({"OnlyShowIn": "XFCE;"}, desktop="XFCE"))

    def test_not_show_in_excludes_xfce(self):
        self.assertFalse(
            autostart_visible({"NotShowIn": "XFCE;"}, desktop="XFCE"))
        self.assertTrue(
            autostart_visible({"NotShowIn": "GNOME;"}, desktop="XFCE"))

    def test_user_entry_replaces_the_system_entry(self):
        system = {"Hidden": "true"}
        user = {"Hidden": "false", "OnlyShowIn": "XFCE;"}
        self.assertFalse(autostart_visible(system, desktop="XFCE"))
        self.assertTrue(autostart_visible(system, user, "XFCE"))


class SessionComponentsTest(unittest.TestCase):
    def test_session_components_are_packaged(self):
        paths = packaged_paths()
        for command in ("/usr/bin/xfce4-session", "/usr/bin/xfsettingsd",
                        "/usr/bin/xfwm4"):
            self.assertIn(command, paths)
        self.assertTrue(
            any(path.startswith("/usr/lib64/libstartup-notification")
                for path in paths),
            "startup-notification runtime library is not packaged")

        for name in ("xfce4-session", "xfce4-settings", "xfwm4",
                     "startup-notification"):
            self.assertTrue(
                (SPECS / name / (name + ".spec")).is_file(), name)

    def test_desktop_profiles_require_the_session_packages(self):
        for name in ("xfce-desktop", "xfce-desktop-core"):
            needed = requires(SPECS / name / (name + ".spec"))
            for dependency in ("xfce4-session", "xfce4-settings", "xfwm4"):
                self.assertIn(dependency, needed, name)

        config = requires(
            SPECS / "tenko-desktop-config" / "tenko-desktop-config.spec")
        self.assertIn("xfce4-session", config)

    def test_desktop_profiles_require_the_session_bus(self):
        for name in ("xfce-desktop", "xfce-desktop-core"):
            needed = requires(SPECS / name / (name + ".spec"))
            self.assertIn("dbus-daemon", needed, name)
            self.assertIn("dbus-x11", needed, name)

    def test_session_checker_is_posix_shell(self):
        script = REPO_ROOT / "scripts" / "fdo_session_check.sh"
        self.assertTrue(script.is_file())
        self.assertTrue(os.access(script, os.X_OK), "script is not executable")
        result = subprocess.run(
            ["sh", "-n", str(script)],
            capture_output=True, text=True,
        )
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_qemu_gate_uses_a_real_login_session(self):
        """The desktop gate must cover the systemd user manager path (#46)."""
        script = read_text(REPO_ROOT / "scripts" / "qemu_fdo_verify.sh")
        self.assertIn("autologin-user", script)
        self.assertIn("fdo-prep.service", script)
        self.assertIn("fdo-check.service", script)
        self.assertIn("xfce-session.target", script)
        self.assertIn("HARNESS-FAIL", script)
        self.assertIn("unix:path=/tmp/dbus-*", script)


if __name__ == "__main__":
    unittest.main()
